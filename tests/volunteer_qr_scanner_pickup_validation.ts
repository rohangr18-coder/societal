// --- TEST 1: QR Code Payload Parsing ---
console.log('--- Test 1: parseDonationQR Payload Decoding ---');

// Case A: Structured JSON payload (generated by ResQBite Donor Display Screen)
const jsonPayload = JSON.stringify({
  app: 'resqbite',
  type: 'pickup',
  donationId: 'donation_alpha_101',
  token: 'PKUP-7X9K-42M1',
  pin: '482910',
});

const resA = parseDonationQR(jsonPayload, mockDonations);
assert(resA.donationId === 'donation_alpha_101', 'Decodes donationId from JSON payload');
assert(resA.token === 'PKUP-7X9K-42M1', 'Decodes verification token from JSON payload');
assert(resA.pin === '482910', 'Decodes 6-digit PIN from JSON payload');
assert(resA.action === 'pickup', 'Identifies pickup action type');
console.log('  ✅ PASSED: JSON payload from donor display screen parsed correctly');

// Case B: URL with query parameter
const urlWithQuery = 'https://resqbite.org/verify?donationId=donation_beta_202&token=PKUP-BETA-88&pin=112233';
const resB = parseDonationQR(urlWithQuery, mockDonations);
assert(resB.donationId === 'donation_beta_202', 'Decodes donationId from query parameter');
assert(resB.token === 'PKUP-BETA-88', 'Decodes token from query parameter');
assert(resB.pin === '112233', 'Decodes PIN from query parameter');
console.log('  ✅ PASSED: Web URL with query parameters parsed correctly');

// Case C: Mobile Deep Link / Custom URI Scheme
